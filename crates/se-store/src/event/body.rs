use super::*;

/// Closed version-1 persisted kind catalogue. Body text is supplied by T once.
/// Exact closed storage/wire kinds; codec spellings are section 20's catalogue.
/// SessionTurn is `session.turn`; general settings have no storage event kind.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum EventKind {
    ProjectRegistered,
    ProjectUpdated,
    ProjectMoved,
    ProjectRemoved,
    PrincipalRegistered,
    PrincipalRenamed,
    AliasImported,
    ProfileSaved,
    GrantRecorded,
    SessionPrepared,
    SessionActivated,
    SessionEnded,
    SessionRevoked,
    CredentialIssued,
    CredentialActivated,
    CredentialRevoked,
    MessageSent,
    WorkMessageSent,
    MessageDelivered,
    MessageRead,
    MessageDismissed,
    MessageSuperseded,
    DecisionProposed,
    DecisionRatified,
    DecisionRejected,
    DecisionRetracted,
    DecisionSuperseded,
    SessionTurn,
    CaptureSource,
    CaptureProgress,
    CaptureFailed,
    CaptureVerified,
    CaptureSuppressed,
    ProcessRegistered,
    ProcessTransition,
    WorkingStateSet,
    CursorRecorded,
    CursorAcknowledged,
    EffectRequested,
    EffectOffered,
    EffectSettled,
    IntegrationRecorded,
    RuntimeOwnerEstablished,
    RuntimeHandoverRecorded,
    BackupRecorded,
    ImportStarted,
    ImportProgress,
    ImportFinished,
    ImportUnreadable,
    LegacyRetained,
    TurnErased,
    MessageErased,
    ErasureRequested,
    ErasureCompleted,
    RecoveryRecorded,
}

#[derive(Clone)]
pub enum EventBody<T> {
    ProjectRegistered {
        project: ProjectId,
        name: String,
        roots: Vec<Root>,
        owner: HumanId,
        history_from: Option<ProjectId>,
        expected: Expected,
    },
    ProjectUpdated {
        project: ProjectId,
        name: String,
        roots: Vec<Root>,
        expected: Expected,
    },
    /// A moved repository: the CLI verified the target's recorded git identity
    /// (matching project, recorded HEAD ancestry) before this revision applied.
    /// The registered name is carried so active-body readers stay uniform; the
    /// store refuses any move that renames the project.
    ProjectMoved {
        project: ProjectId,
        name: String,
        from: Vec<Root>,
        to: Root,
        head: Option<String>,
        branch: Option<String>,
        expected: Expected,
    },
    ProjectRemoved {
        project: ProjectId,
        expected: Expected,
        witnesses: Vec<EventId>,
        preserved: Vec<String>,
    },
    PrincipalRegistered {
        principal: Actor,
        kind: PrincipalKind,
        owner: HumanId,
        created_by: Option<Actor>,
        name: String,
        role: String,
        expected: Expected,
    },
    PrincipalRenamed {
        principal: Actor,
        name: String,
        expected: Expected,
    },
    AliasImported {
        alias: String,
        principal: Actor,
        source: EventId,
        expected: Expected,
    },
    ProfileSaved {
        agent: AgentId,
        profile: Profile,
        expected: Expected,
    },
    GrantRecorded {
        principal: Actor,
        key: GrantKey,
        active: bool,
        expected: Expected,
    },
    SessionPrepared {
        session: SessionId,
        agent: AgentId,
        provider: Provider,
        surface: Option<SessionSurface>,
        native_ref: String,
        consent: Consent,
        generation: u64,
        expected: Expected,
    },
    SessionActivated {
        session: SessionId,
        expected: Expected,
        incumbent: Option<(SessionId, Revision)>,
        process: Option<LifecycleId>,
        containment: ContainmentFact,
        witnesses: Vec<EventId>,
    },
    SessionEnded {
        session: SessionId,
        expected: Expected,
        reason: T,
        final_turn: Option<EventId>,
        final_cursor: Option<EventId>,
    },
    SessionRevoked {
        session: SessionId,
        expected: Expected,
        reason: T,
    },
    CredentialIssued {
        credential: RecordId,
        session: SessionId,
        purpose: String,
        secret_sha256: [u8; 32],
        expires_at_us: i64,
        activation_deadline_us: i64,
        expected: Expected,
    },
    CredentialActivated {
        credential: RecordId,
        session: SessionId,
        expected: Expected,
        first_request: RecordId,
    },
    CredentialRevoked {
        credential: RecordId,
        expected: Expected,
        reason: T,
    },
    MessageSent {
        message: MessageId,
        recipient: Actor,
        kind: String,
        body: T,
        refs: Vec<EventId>,
        reply_to: Option<MessageId>,
        quiet: bool,
    },
    WorkMessageSent {
        message: MessageId,
        work: se_types::WorkAddressing,
        kind: String,
        body: T,
        refs: Vec<EventId>,
        reply_to: Option<MessageId>,
        quiet: bool,
    },
    MessageDelivered {
        message: MessageId,
        recipient: Actor,
        evidence: EventId,
    },
    MessageRead {
        message: MessageId,
        recipient: Actor,
    },
    MessageDismissed {
        message: MessageId,
        recipient: Actor,
    },
    MessageSuperseded {
        message: MessageId,
        replacement: MessageId,
        expected: Expected,
    },
    DecisionProposed {
        decision: DecisionId,
        key: String,
        statement: T,
        rationale: Option<T>,
        prior: Option<DecisionId>,
        kind: DecisionKind,
    },
    DecisionRatified {
        decision: DecisionId,
        expected: Expected,
        approval: EventId,
    },
    DecisionRejected {
        decision: DecisionId,
        expected: Expected,
        reason: T,
    },
    DecisionRetracted {
        decision: DecisionId,
        expected: Expected,
        reason: T,
    },
    DecisionSuperseded {
        prior: DecisionId,
        replacement: DecisionId,
        prior_expected: Revision,
        replacement_expected: Revision,
        approval: EventId,
    },
    SessionTurn {
        turn: RecordId,
        agent: AgentId,
        session: SessionId,
        provider: Provider,
        vendor_ref: String,
        role: Role,
        text: T,
        evidence: SourceEvidence,
    },
    CaptureSource {
        source: RecordId,
        session: SessionId,
        consent: Consent,
        native_ref: String,
        incarnation: Vec<u8>,
        expected: Expected,
    },
    CaptureProgress {
        source: RecordId,
        expected: Expected,
        incarnation: Vec<u8>,
        old_offset: u64,
        new_offset: u64,
        last_turn: RecordId,
        /// Current source range when the turn was retained from an earlier engine session.
        replay_evidence: Option<SourceEvidence>,
    },
    /// A trusted final reader reached EOF at this exact committed source cursor.
    CaptureVerified {
        source: RecordId,
        session: SessionId,
        offset: u64,
    },
    CaptureFailed {
        source: RecordId,
        session: SessionId,
        from_offset: u64,
        to_offset: u64,
        code: se_types::Code,
        cause: String,
        retry: se_types::Retry,
    },
    CaptureSuppressed {
        source: RecordId,
        session: SessionId,
        expected: Expected,
        reason: String,
        from_offset: u64,
        to_offset: u64,
        count: u64,
    },
    ProcessRegistered {
        identity: Box<ProcessIdentityRecord>,
        initial: ProcessState,
    },
    ProcessTransition {
        process: LifecycleId,
        identity: Box<ProcessIdentityRecord>,
        expected: Expected,
        from: ProcessState,
        to: ProcessState,
        observation: EventId,
        outcome: String,
        containment: ContainmentFact,
    },
    WorkingStateSet {
        agent: AgentId,
        text: T,
        expected: Expected,
    },
    CursorRecorded {
        cursor: Box<CursorRecord>,
    },
    CursorAcknowledged {
        cursor: RecordId,
        expected: Revision,
        evidence: EventId,
    },
    EffectRequested {
        principal: Option<Actor>,
        effect: RecordId,
        kind: EffectKind,
        intent: EffectIntent,
        cause: EventId,
        request_key: IdempotencyKey,
    },
    EffectOffered {
        effect: RecordId,
        principal: Actor,
        attempt: RecordId,
        evidence: crate::mail::OfferEvidence,
    },
    EffectSettled {
        effect: RecordId,
        expected: Expected,
        outcome: EffectOutcome,
        evidence: Vec<EventId>,
        failure: Option<String>,
        attempts: u32,
    },
    IntegrationRecorded {
        integration: RecordId,
        path: NativePath,
        key: String,
        marker: String,
        prior_sha256: Option<[u8; 32]>,
        written_sha256: Option<[u8; 32]>,
        state: IntegrationState,
        witness: EventId,
        expected: Expected,
    },
    /// Initial or checked cold owner admission, never an implicit handover abort.
    RuntimeOwnerEstablished {
        epoch: HostEpoch,
        generation: Generation,
        expected_owner_generation: Option<Generation>,
        expected: Expected,
        witnesses: Vec<EventId>,
        recovered: Option<Box<RuntimeRecoveredTransfer>>,
    },
    RuntimeHandoverRecorded {
        record: Box<RuntimeHandoverRecord>,
        expected: Expected,
        witnesses: Vec<EventId>,
    },
    BackupRecorded {
        generation: RecordId,
        through: crate::StorePosition,
        bytes: u64,
        sha256: [u8; 32],
        schema_version: u32,
        witness: EventId,
    },
    ImportStarted {
        import: RecordId,
        source: NativePath,
        source_sha256: [u8; 32],
        format: String,
        policy_version: u32,
    },
    ImportProgress {
        checkpoint: ImportCheckpoint,
        counts: ImportCounts,
    },
    ImportFinished {
        import: RecordId,
        expected: Expected,
        counts: ImportCounts,
        complete: bool,
        omissions: Vec<RecordId>,
    },
    ImportUnreadable {
        import: RecordId,
        family: crate::ImportFamily,
        evidence: SourceEvidence,
        code: String,
    },
    LegacyRetained {
        import: RecordId,
        family: crate::ImportFamily,
        format_version: u32,
        legacy_id: String,
        mapped_id: crate::import::LegacyTarget,
        source: SourceEvidence,
        bytes: Option<LegacyBytes>,
        /// Duplicate history refers to the original owning payload instead of
        /// making another undeclared text copy.
        retained_from: Option<EventId>,
    },
    TurnErased {
        target: EventId,
        erasure: RecordId,
        original_bytes: u64,
        by: HumanId,
    },
    MessageErased {
        target: EventId,
        erasure: RecordId,
        original_bytes: u64,
        by: HumanId,
    },
    ErasureRequested {
        erasure: RecordId,
        targets: Vec<crate::EraseTarget>,
        residuals: Vec<crate::ResidualCopy>,
    },
    ErasureCompleted {
        erasure: RecordId,
        manifest_sha256: [u8; 32],
        incarnation: u64,
        witnesses: Vec<EventId>,
    },
    RecoveryRecorded {
        recovery: RecordId,
        request_key: IdempotencyKey,
        source: Option<StoreId>,
        source_incarnation: Option<u64>,
        source_artifact: SourceEvidence,
        target: StoreId,
        target_incarnation: u64,
        backup: RecordId,
        restored_through: crate::StorePosition,
        loss: crate::RestoreLoss,
        schema_version: u32,
        witnesses: Vec<EventId>,
        /// Complete original se.restore/v1 JSON, one immutable payload (max 1 MiB).
        receipt: T,
    },
}
